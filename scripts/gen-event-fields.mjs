// Writes src/chain/runtime/eventFields.generated.ts: every runtime event's field names,
// from a node's metadata. Run against a node on the target runtime:
//   node scripts/gen-event-fields.mjs http://127.0.0.1:9944
import { writeFileSync } from 'node:fs';
import { decAnyMetadata, unifyMetadata } from '@polkadot-api/substrate-bindings';

const url = process.argv[2] ?? 'http://127.0.0.1:9944';
const rpc = async (method, params = []) => {
    const res = await fetch(url, {
        method: 'POST',
        headers: { 'content-type': 'application/json' },
        body: JSON.stringify({ id: 1, jsonrpc: '2.0', method, params }),
    });
    const body = await res.json();
    if (body.error) throw new Error(`${method}: ${body.error.message}`);
    return body.result;
};

const { specVersion } = await rpc('state_getRuntimeVersion');
const hex = await rpc('state_call', ['Metadata_metadata_at_version', '0x0f000000']);
const bytes = Buffer.from(hex.slice(2), 'hex');
// Option<OpaqueMetadata>: 0x01, then a compact length.
const mode = bytes[1] & 3;
const offset = 1 + (mode === 0 ? 1 : mode === 1 ? 2 : 4);
const metadata = unifyMetadata(decAnyMetadata(new Uint8Array(bytes.subarray(offset))));

const out = {};
for (const pallet of metadata.pallets) {
    const id = pallet.events?.type ?? pallet.events;
    const def = id == null ? null : metadata.lookup[id]?.def;
    if (def?.tag !== 'variant') continue;
    out[pallet.name] = Object.fromEntries(
        def.value.map((v) => [v.name, v.fields.map((f, i) => f.name ?? String(i))])
    );
}

const body = Object.entries(out)
    .map(([pallet, events]) => {
        const lines = Object.entries(events).map(
            ([name, fields]) => `        ${name}: [${fields.map((f) => `'${f}'`).join(', ')}],`
        );
        return `    ${pallet}: {\n${lines.join('\n')}\n    },`;
    })
    .join('\n');

writeFileSync(
    new URL('../src/chain/runtime/eventFields.generated.ts', import.meta.url),
    `// Generated by scripts/gen-event-fields.mjs from runtime spec ${specVersion}. Do not edit.\n\n` +
        `/** The runtime spec these field names were read from. */\n` +
        `export const EVENT_FIELDS_SPEC = ${specVersion};\n\n` +
        `/** Every runtime event's fields, by pallet and event, as the metadata names them. */\n` +
        `export const EVENT_FIELDS = {\n${body}\n} as const;\n`
);
console.log(`spec ${specVersion}: ${Object.keys(out).length} pallets`);
